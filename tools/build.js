// Bundles src/*.js (ES modules) into one classic script, tyrrainy.js, so the game
// also runs when index.html is opened straight from disk (file://), where
// browsers refuse to load ES modules.
import { readFileSync, writeFileSync } from 'node:fs';

const ORDER = ['hex', 'rng', 'data', 'culture', 'mapgen', 'diplomacy', 'economy', 'trade', 'vassals', 'upkeep', 'projects', 'game', 'ai', 'render', 'main'];
let out = '// GENERATED by tools/build.js from src/ — do not edit by hand.\n(function () {\n"use strict";\n';
for (const m of ORDER) {
  let src = readFileSync(new URL(`../src/${m}.js`, import.meta.url), 'utf8');
  src = src.replace(/^import[\s\S]*?from\s+['"][^'"]+['"];[ \t]*$/gm, '');
  src = src.replace(/^export\s+(?=(const|function|class|let|async))/gm, '');
  out += `\n// ---- src/${m}.js ----\n` + src;
}
out += '\n})();\n';
writeFileSync(new URL('../tyrrainy.js', import.meta.url), out);
console.log(`wrote tyrrainy.js (${(out.length / 1024).toFixed(1)} KB)`);
